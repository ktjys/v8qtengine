// Helper to evaluate all 21 items through the V8 5-stage pipeline
export function runV8PipelineOnSeedData(
  existingClassifications: Record<string, AssetClassification> = {}
): {
  evaluations: FullTickerEvaluation[];
  watchlist: WatchlistItem[];
} {
  const evaluatedAt = new Date().toISOString();
  const watchlist: WatchlistItem[] = [];
  const evaluations: FullTickerEvaluation[] = [];

  for (const item of INITIAL_WATCHLIST_RAW) {
    watchlist.push({
      ticker: item.ticker,
      name: item.name,
      is_active: true,
      memo: item.memo,
      created_at: '2026-01-10T09:00:00Z',
    });

    // 1. Classification
    const classification = classifyAsset(
      item.ticker,
      item.metadata,
      existingClassifications[item.ticker]
    );

    // 2. Opportunity
    const opportunity = calculateOpportunity(classification, item.indicators);

    // 3. Risk
    const risk = calculateRisk(classification, item.riskInputs);

    // 4. Decision
    const decision = makeDecision(classification, opportunity, risk);

    // 5. Signal check
    const signal_generated = decision.actionable;

    evaluations.push({
      ticker: item.ticker,
      name: item.name,
      price: item.price,
      change1d: item.change1d,
      evaluated_at: evaluatedAt,
      classification,
      opportunity,
      risk,
      decision,
      signal_generated,
      raw_metadata: item.metadata,
    });
  }

  return { evaluations, watchlist };
}

